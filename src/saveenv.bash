# SaveEnv v0.1.0 - Source this file in Bash; do not execute it as a subprocess.
# shellcheck shell=bash

if [[ -z "${BASH_VERSION:-}" ]]; then
    return 0 2>/dev/null || exit 0
fi

_saveenv_entries_dir="${HOME}/.config/saveenv/entries"

_saveenv_help() {
    cat <<'HELP'
SaveEnv v0.1.0 - Remember project directories and active Python environments.

Usage:
  saveenv NAME         Register current directory + activated venv/Conda environment
  saveenv list         List registered shortcuts
  saveenv show NAME    Show the generated Bash function
  saveenv remove NAME  Remove a registered shortcut
  saveenv help         Show help

After registration, enter NAME directly to jump to the project and activate its environment.
HELP
}

_saveenv_valid_name() {
    [[ "$1" =~ ^[a-zA-Z_][a-zA-Z0-9_]*$ ]] || return 1
    case "$1" in
        saveenv|list|ls|show|remove|rm|help) return 1 ;;
    esac
    return 0
}

_saveenv_register() {
    if [[ $# -ne 1 ]] || ! _saveenv_valid_name "$1"; then
        printf 'saveenv: invalid name. Use letters, numbers and underscores (not starting with a digit).\n' >&2
        return 2
    fi

    local name="$1" target="${_saveenv_entries_dir}/$1.bash"
    if [[ -e "$target" ]] || type -t "$name" >/dev/null 2>&1; then
        printf 'saveenv: shortcut or shell command already exists: %s\n' "$name" >&2
        return 1
    fi

    local project activation env_label qproject qenv
    project="$(pwd -P)" || return 1
    printf -v qproject '%q' "$project"

    if [[ -n "${VIRTUAL_ENV:-}" ]]; then
        if [[ ! -f "${VIRTUAL_ENV%/}/bin/activate" ]]; then
            printf 'saveenv: VIRTUAL_ENV points to an environment with no bin/activate.\n' >&2
            return 1
        fi
        printf -v qenv '%q' "${VIRTUAL_ENV%/}/bin/activate"
        activation="source $qenv"
        env_label='venv/virtualenv'
    elif [[ -n "${CONDA_PREFIX:-}" ]]; then
        if [[ ! -d "$CONDA_PREFIX" ]]; then
            printf 'saveenv: CONDA_PREFIX does not exist.\n' >&2
            return 1
        fi
        printf -v qenv '%q' "$CONDA_PREFIX"
        activation="conda activate $qenv"
        env_label='conda'
    else
        printf 'saveenv: no active venv/virtualenv or Conda environment detected.\n' >&2
        return 1
    fi

    mkdir -p -m 700 -- "$_saveenv_entries_dir" || return 1
    local temp
    temp="$(mktemp "${_saveenv_entries_dir}/.new.XXXXXXXX")" || return 1
    chmod 600 "$temp" || { rm -f -- "$temp"; return 1; }
    if ! {
        printf '# Generated by SaveEnv. Do not edit while the shell is running.\n'
        printf '%s() {\n' "$name"
        printf '    builtin cd -- %s || return\n' "$qproject"
        printf '    %s\n' "$activation"
        printf '}\n'
    } > "$temp"; then
        rm -f -- "$temp"
        return 1
    fi

    if [[ -e "$target" ]]; then
        rm -f -- "$temp"
        printf 'saveenv: shortcut already exists: %s\n' "$name" >&2
        return 1
    fi
    if ! mv -- "$temp" "$target"; then
        rm -f -- "$temp"
        return 1
    fi
    # shellcheck disable=SC1090
    source "$target" || return 1
    printf 'Saved: %s -> %s (%s)\n' "$name" "$project" "$env_label"
    if [[ "$env_label" == conda && "${CONDA_DEFAULT_ENV:-}" == base ]]; then
        printf 'Note: you saved the Conda base environment.\n'
    fi
}

_saveenv_list() {
    local entry found=0
    for entry in "$_saveenv_entries_dir"/*.bash; do
        [[ -f "$entry" ]] || continue
        printf '%s\n' "${entry##*/}" | sed 's/\.bash$//'
        found=1
    done
    if [[ $found -eq 0 ]]; then
        printf 'No saved shortcuts. Run: saveenv NAME\n'
    fi
}

_saveenv_show() {
    if [[ $# -ne 1 ]] || ! _saveenv_valid_name "$1"; then
        printf 'Usage: saveenv show NAME\n' >&2
        return 2
    fi
    local file="${_saveenv_entries_dir}/$1.bash"
    if [[ ! -f "$file" ]]; then
        printf 'saveenv: shortcut not found: %s\n' "$1" >&2
        return 1
    fi
    cat -- "$file"
}

_saveenv_remove() {
    if [[ $# -ne 1 ]] || ! _saveenv_valid_name "$1"; then
        printf 'Usage: saveenv remove NAME\n' >&2
        return 2
    fi
    local file="${_saveenv_entries_dir}/$1.bash"
    if [[ ! -f "$file" ]]; then
        printf 'saveenv: shortcut not found: %s\n' "$1" >&2
        return 1
    fi
    rm -- "$file" || return 1
    unset -f "$1"
    printf 'Removed shortcut: %s\n' "$1"
}

saveenv() {
    local command="${1:-help}"
    case "$command" in
        help|-h|--help) _saveenv_help ;;
        list|ls) if [[ $# -ne 1 ]]; then _saveenv_help; return 2; fi; _saveenv_list ;;
        show) shift; _saveenv_show "$@" ;;
        remove|rm) shift; _saveenv_remove "$@" ;;
        *) _saveenv_register "$@" ;;
    esac
}

# Restore registered Bash functions for every new interactive shell.
_saveenv_entry=''
for _saveenv_entry in "$_saveenv_entries_dir"/*.bash; do
    [[ -f "$_saveenv_entry" ]] || continue
    # shellcheck disable=SC1090
    source "$_saveenv_entry"
done
unset _saveenv_entry
